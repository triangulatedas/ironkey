#!/usr/bin/env python3
"""
Generate tests/vectors.inc from the original Python implementation.

Loads ironkey_unlock.py (github.com/wltechblog/ironkey-unlocker), replaces its
I/O and randomness with fixed inputs, and records what it produces. The C++
tests replay the same inputs and must produce byte-identical output.

pycryptodome is not needed: a small shim backed by `cryptography` stands in.

Usage:
    python3 tools/gen_vectors.py path/to/ironkey_unlock.py > tests/vectors.inc
"""

import importlib.util
import random
import sys
import types

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def install_crypto_shim():
    class AES:
        MODE_ECB = 1

        @staticmethod
        def new(key, mode):
            enc = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
            return types.SimpleNamespace(encrypt=enc.update)

    crypto = types.ModuleType("Crypto")
    cipher = types.ModuleType("Crypto.Cipher")
    util = types.ModuleType("Crypto.Util")
    number = types.ModuleType("Crypto.Util.number")
    cipher.AES = AES
    number.getPrime = lambda bits: None
    number.inverse = lambda a, m: pow(a, -1, m)
    sys.modules.update({
        "Crypto": crypto, "Crypto.Cipher": cipher,
        "Crypto.Util": util, "Crypto.Util.number": number,
    })


def load_original(path):
    install_crypto_shim()
    spec = importlib.util.spec_from_file_location("ironkey_unlock", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def is_probable_prime(n, rng):
    if n < 4:
        return n in (2, 3)
    d, s = n - 1, 0
    while d % 2 == 0:
        d //= 2
        s += 1
    for _ in range(40):
        a = rng.randrange(2, n - 2)
        x = pow(a, d, n)
        if x in (1, n - 1):
            continue
        for _ in range(s - 1):
            x = pow(x, 2, n)
            if x == n - 1:
                break
        else:
            return False
    return True


def fixed_rsa512(rng):
    e = 65537
    while True:
        primes = []
        while len(primes) < 2:
            c = rng.getrandbits(256) | (3 << 254) | 1
            if is_probable_prime(c, rng):
                primes.append(c)
        p, q = primes
        n = p * q
        phi = (p - 1) * (q - 1)
        if n.bit_length() == 512 and phi % e != 0:
            le = lambda v: v.to_bytes(64, "little")
            return le(n), le(e), le(pow(e, -1, phi))


class FakeIo:
    """Stands in for os/hidraw: records writes, serves canned feature reads."""

    def __init__(self, ik, urandom_chunks, feature_responses, pvc_random):
        self.ik = ik
        self.urandom_chunks = list(urandom_chunks)
        self.feature_responses = list(feature_responses)
        self.pvc_random = iter(pvc_random)
        self.writes = []

    def __enter__(self):
        ik = self.ik
        self.saved = (ik.os, ik.read_interrupt, ik.hid_set_feature,
                      ik.hid_get_feature, ik.drain_interrupts, ik.time,
                      random.seed, random.getrandbits)
        ik.os = types.SimpleNamespace(write=self._write, urandom=self._urandom)
        ik.read_interrupt = lambda fd, timeout=2.0: bytes(64)
        ik.hid_set_feature = lambda fd, data: self.writes.append(("feature", bytes(data)))
        ik.hid_get_feature = self._get_feature
        ik.drain_interrupts = lambda fd, timeout=0.2: None
        ik.time = types.SimpleNamespace(sleep=lambda s: None)
        random.seed = lambda *a, **k: None
        random.getrandbits = lambda bits: next(self.pvc_random)
        return self

    def __exit__(self, *exc):
        ik = self.ik
        (ik.os, ik.read_interrupt, ik.hid_set_feature, ik.hid_get_feature,
         ik.drain_interrupts, ik.time, random.seed, random.getrandbits) = self.saved

    def _write(self, fd, data):
        assert data[0] == 0 and len(data) == 65
        self.writes.append(("output", bytes(data[1:])))
        return len(data)

    def _urandom(self, n):
        chunk = self.urandom_chunks.pop(0)
        assert len(chunk) == n
        return chunk

    def _get_feature(self, fd, size=512):
        return self.feature_responses.pop(0).ljust(size, b"\x00")


def hexs(b):
    return '"' + b.hex() + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ik = load_original(sys.argv[1])
    rng = random.Random(0x1234)
    rb = lambda n: bytes(rng.getrandbits(8) for _ in range(n))
    out = []
    emit = out.append

    emit("// Generated by tools/gen_vectors.py from the original ironkey_unlock.py.")
    emit("// Do not edit by hand.\n")

    # clamp()
    emit("inline const ClampCase kClampCases[] = {")
    for top in (0x00, 0x01, 0x80, 0xFF):
        for leading_zeros in (0, 1, 5):
            buf = rb(64 - leading_zeros) + bytes(leading_zeros)
            n_dev = rb(63) + bytes([top])
            emit(f"    {{{hexs(buf)}, {hexs(n_dev)}, {hexs(ik.clamp(buf, n_dev))}}},")
    emit(f"    {{{hexs(bytes(64))}, {hexs(rb(63) + b'\\x10')}, {hexs(bytes(64))}}},")
    emit("};\n")

    # encrypt_pvc_key()
    emit("inline const PvcCase kPvcCases[] = {")
    for _ in range(3):
        shared = rb(16)
        pvc_random = rb(32)
        with FakeIo(ik, [], [], pvc_random):
            result = ik.encrypt_pvc_key(ik.PVC0_KEY, shared)
        emit(f"    {{{hexs(shared)}, {hexs(pvc_random)}, {hexs(result)}}},")
    emit("};\n")

    # send_hid() framing
    emit("inline const FrameCase kFrameCases[] = {")
    frames = [
        (0x81, 0x00, "read", b"", 128, bytes(8)),
        (0x82, 0x00, "write", rb(128), 0, bytes(8)),
        (0x8B, 0x00, "none", b"", 0, bytes([0, 3, 0, 0, 0, 0, 0, 0])),
        (0x8F, 0x00, "write", rb(64), 0, bytes([2, 0, 0, 0, 0, 0, 0, 0])),
        (0xA4, 0x00, "write", rb(16), 16, bytes([0, 0, 0, 6, 0, 0, 0, 0])),
        (0x89, 0x00, "none", b"", 0, bytes(8)),
        (0x21, 0x5A, "read", b"", 0x200, bytes(range(1, 9))),
    ]
    for sub, cdb2, direction, data, data_len, cdb in frames:
        with FakeIo(ik, [], [b""], []) as io:
            ik.send_hid(None, sub, cdb2, direction, data=data,
                        data_len=data_len, cdb3_10=cdb)
        report = io.writes[0][1]
        emit(f'    {{0x{sub:02X}, 0x{cdb2:02X}, Direction::{direction.capitalize()}, '
             f'{hexs(data)}, {data_len}, {hexs(cdb)}, {hexs(report)}}},')
    emit("};\n")

    # Full rsa_handshake() + send_unlock() transcript
    host_n, host_e, host_d = fixed_rsa512(rng)
    dev_n, dev_e, _dev_d = fixed_rsa512(rng)
    r1, r2, pvc_random = rb(64), rb(64), rb(32)
    responses = [dev_n + dev_e, rb(64), rb(64), rb(64)]  # FF81, FF84, FF85, FF88
    password = "Corr3ct-Horse!"
    ik.generate_rsa512 = lambda: (host_n, host_e, host_d)
    with FakeIo(ik, [r1, r2], responses, pvc_random) as io:
        shared = ik.rsa_handshake(None)
        ik.send_unlock(None, shared, password)

    emit("namespace transcript {")
    emit(f"inline const char* kHostN = {hexs(host_n)};")
    emit(f"inline const char* kHostE = {hexs(host_e)};")
    emit(f"inline const char* kHostD = {hexs(host_d)};")
    emit(f"inline const char* kRandomStream = {hexs(r1 + r2 + pvc_random)};")
    emit(f'inline const char* kPassword = "{password}";')
    emit(f"inline const char* kSharedSecret = {hexs(shared)};")
    emit("inline const char* kFeatureResponses[] = {")
    for r in responses:
        emit(f"    {hexs(r)},")
    emit("};")
    emit("inline const TranscriptWrite kWrites[] = {")
    for kind, data in io.writes:
        emit(f"    {{WriteKind::{kind.capitalize()}, {hexs(data)}}},")
    emit("};")
    emit("}  // namespace transcript")

    print("\n".join(out))


if __name__ == "__main__":
    main()
